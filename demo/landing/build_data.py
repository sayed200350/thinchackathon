"""Generate data.js for the landing page from the real v1 engine.

Run from the repository root:  python3 demo/landing/build_data.py
"""
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from engine.policy import decide, _fact  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SOURCES = [ROOT / "data/taktile/labelled_development_cases.csv",
           ROOT / "data/taktile/unlabelled_practice_cases.csv"]
OUT = Path(__file__).with_name("data.js")
V1_THRESHOLD = 1500


def simulate(c, threshold):
    """Mirror of simulate() in landing.js, used to verify it reproduces v1."""
    if c["status"] == "closed":
        return c["v1"]
    if c["base"] == "human_review":
        return "human_review"
    if c["quote"] is not None and c["quote"] > threshold:
        return "human_review"
    if c["quote"] is None:
        return "request_information"
    return c["base"]


claims = []
for source in SOURCES:
    with source.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            row.pop("expected_v1", None)  # never ship development labels
            v1 = decide(row)
            # Same claim with a zero quote: isolates every route reason except the quote.
            base = decide({**row, "quote_eur": "0"})
            quote = _fact("quote_eur", row.get("quote_eur"))
            claim = {
                "id": v1["case_id"],
                "status": v1["case_status"],
                "summary": row.get("claim_summary", "").strip(),
                "quote": float(quote) if quote is not None else None,
                "v1": v1["recommendation"],
                "rule": v1["matched_rule"],
                "explanation": v1["explanation"],
                "base": base["recommendation"],
                "baseExplanation": base["explanation"],
            }
            assert simulate(claim, V1_THRESHOLD) == v1["recommendation"], claim["id"]
            claims.append(claim)

OUT.write_text("// Generated by build_data.py from the real v1 engine. Do not edit.\n"
               f"window.POLICY_REPLAY_CLAIMS = {json.dumps(claims, ensure_ascii=False, indent=1)};\n",
               encoding="utf-8")
print(f"Wrote {len(claims)} claims to {OUT.relative_to(ROOT)}")
